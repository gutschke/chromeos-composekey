let composeFile;
let composeKey;
let composeOnKeyUp = false;
let composeKeyDown = false;
let composing;
let keepModifier;
let keyDownSuppressed = new Set();
let rootState;

/**
 * A list of sequences matching the current input, in the order in which those
 * sequences were defined in the compose file. In case of collision, the last
 * sequence definition wins.
 * @return {Promise<Array<EventState!>!>!}
 */
let states = [];

// Initialize all values from storage each time the worker starts up.
// Variables aren't preserved otherwise when dealing with a
// ServiceWorker, you see, and a ServiceWorker can go away at just about
// any time.
const initPromise =
    chrome.storage.sync
        .get(
            // keepModifier defaults to false, as it did through v1.8
            // (`localStorage.getItem('keepModifier') == "true"`). With true,
            // holding Compose while typing the sequence cannot work: the held
            // key reaches the app as Alt and the next key cancels compose. The
            // MV3 port flipped this default, and could not migrate the old
            // localStorage value, so every user lost hold-to-compose.
            {'key': 'AltRight', 'composeFile': null, 'keepModifier': false})
        .then((options) => {
          composeKey = options.key;
          keepModifier = options.keepModifier;

          if (options.composeFile === null) {
            return chrome.storage.local.get(
                {'composeFile': defaultComposeFile});
          } else {
            composeFile = options.composeFile;
            return Promise.resolve(undefined);
          }
        })
        .then((options) => {
          if (options !== undefined) {
            composeFile = options.composeFile;
          }

          return chrome.storage.session.get({
            'keyDownSuppressed': [],
            'statePaths': null,
            'composing': false,
            'composeOnKeyUp': false,
            'composeKeyDown': false,
            'held': null,
            'contextID': 0
          });
        })
        .then((options) => {
          contextID = options.contextID;
          composeKeyDown = options.composeKeyDown;
          held = options.held;
          keyDownSuppressed = new Set(options.keyDownSuppressed);
          composing = options.composing;
          composeOnKeyUp = options.composeOnKeyUp;

          // Parsed here, inside initPromise, so no listener can see a
          // half-initialised tree.
          loadComposeFileAtStartup(options.statePaths);
        });

// Whole-tree copies written by earlier versions; no longer read.
chrome.storage.session.remove(['rootState', 'states']);

// Listen for config updates from the options page.
chrome.runtime.onMessage.addListener((message, sender, sendResponse) => {
  if (!message || !message.command) {
    sendResponse({error: 'No command?'});
    return true;
  }

  switch (message.command) {
    case 'getOptions': {
      sendResponse({composeKey, composeFile, keepModifier});
      return true;
    }
    case 'getFileStatus': {
      sendResponse(fileStatus);
      return true;
    }
    case 'storeKeyOptions': {
      if (!message.data) {
        sendResponse({error: 'No data sent with storeKeyOptions'});
        return true;
      }

      setKey(message.data);
      sendResponse({result: 'OK'});
      return true;
    }
    case 'storeComposeFile': {
      if (!message.data) {
        sendResponse({error: 'No data sent with storeComposeFile'});
        return true;
      }

      setComposeFile(message.data);
      sendResponse({result: 'OK'});
      return true;
    }
    case 'clearComposeFile': {
      clearComposeFile();
      sendResponse({result: 'OK'});
      return true;
    }
    default: {
      sendResponse({error: `Unknown command ${message.command}`});
      return true;
    }
  }
});

/**
 * A result held back because its sequence is complete but also the start of a
 * longer one (e.g. ":-" → ÷ while ":-)" → 🙂 exists): {path, tail}, where path
 * locates its state in the tree and tail is what has been typed since. Kept
 * until the longer sequence completes (dropped) or fails (held result + tail
 * committed: longest match, then the rest as typed). Persisted, so it survives
 * a worker restart.
 *
 * This cannot be derived from `states` alone. Once the input moves more
 * than one key past the held point (e.g. "|B" ฿ → "|BD" on the way to "|BDM"),
 * the current states no longer carry the result; deriving it from them
 * would lose both the ฿ and the keys typed after it.
 * @type {?{path: !Array, tail: string}}
 */
let held = null;

/** @param {?{path: !Array, tail: string}} value */
function setHeld(value) {
  chrome.storage.session.set({'held': value});
  held = value;
}

/** @return {?{result: !Result, tail: string}} */
function heldResult() {
  if (held === null) return null;
  const state = stateAtPath(rootState, held.path);
  return state && state.result ? {result: state.result, tail: held.tail} : null;
}

/**
 * Commits a held result, the keys typed after it, and `extra`, in one call
 * where possible.
 */
function commitHeld(h, extra, keyData) {
  if (h.result.string !== null) {
    new Result(h.result.string + h.tail + extra, null).send(keyData);
  } else {
    h.result.send(keyData);
    if (h.tail + extra) new Result(h.tail + extra, null).send(keyData);
  }
}

/**
 * @param {Array<EventState!>!} candidates
 * @return {boolean} True if any candidate can still be extended.
 */
function canContinue(candidates) {
  return candidates.some((c) => Object.keys(c.nextKeys).length > 0);
}

/**
 * True if the key produces a single character that can be committed as text.
 * Alt is allowed, since in hold-to-compose mode every key arrives with Alt.
 * @param {Object!} keyData
 * @return {boolean}
 */
function isPrintable(keyData) {
  return [...keyData.key].length == 1 && !keyData.ctrlKey && !keyData.metaKey;
}

