/** @type {function(string)} */
let onComposeKeyLoaded = null;

const defaultComposeFile = 'include "%L"\n';

/**
 * Sets the contents of the compose file (to local or sync storage) and parses
 * it into the root state (to session storage).
 * @param {string} content
 */
function setComposeFile(content) {
  fileStatus = {
    warnings: [],
    errors: [],
  };

  // The raw contents of the compose file get stored away, to be parsed into an
  // EventState tree on load.
  storeComposeFile(content);

  const parsed = parseComposeFile(content);
  rootState = parsed.root;
  composeFile = content;
  fileStatus.warnings = parsed.warnings;
  fileStatus.errors = parsed.errors;
  resetState();
}

/**
 * Stores the contents of the compose file to either local or sync storage,
 * depending on whether or not it fits in sync storage. If it also doesn't fit
 * in local storage, then we've got problems.
 * @param {string} content
 */
function storeComposeFile(content) {
  chrome.storage.sync.set({composeFile: content}, () => {
    if (!chrome.runtime.lastError) {
      console.log(
          'Stored compose file to Chrome sync (%d characters).',
          lengthInCodepoints(content));
      composeFile = content;
      return;
    }

    console.warn(
        'Failed to store compose file to Chrome sync:',
        chrome.runtime.lastError);
    console.warn('Falling back to local storage and clearing sync storage.');
    chrome.storage.local.set({'composeFile': content});
    console.log(
        'Stored compose file to local storage (%d characters).',
        lengthInCodepoints(content));
    composeFile = content;

    // Remove the previous compose file, if any, from storage. If the new
    // compose file is too large to sync, we want to fall back to local copies
    // instead of loading an outdated configuration from sync.
    chrome.storage.sync.remove('composeFile', () => {
      if (chrome.runtime.lastError) {
        console.warn(
            'Failed to remove stored compose file from Chrome sync:',
            chrome.runtime.lastError);
      }
    });
  });
}

/**
 * Clears the compose file and resets the state. This clears both sync and local
 * storage, then resets the contents to the default compose file via
 * setComposeFile, with the implications therein regarding whether it goes to
 * sync or local storage.
 *
 * As a side effect of reloading the default compose file, this will also
 * ultimately repopulate the sync and/or local storage with the default compose
 * file, and re-parse that into the root state.
 */
function clearComposeFile() {
  chrome.storage.sync.remove('composeFile');
  chrome.storage.local.remove('composeFile');
  setComposeFile(defaultComposeFile);
  console.log('Compose file reset to default.');
}

/**
 * Parses the stored compose file into rootState when the worker starts.
 *
 * This does not go through setComposeFile(), which the previous
 * start-up code did. A worker start is not a settings change, and Chrome starts
 * workers all the time (after every idle shutdown):
 *  - setComposeFile() calls resetState(), which abandoned any composition in
 *    progress whenever the worker had been stopped mid-sequence;
 *  - it re-stored the file to sync storage on every start; and the old
 *    fallback path re-read *sync* instead of local, so a compose file too large
 *    for sync (kept in local storage) was replaced by the default file on the
 *    next start, and the default then won from sync for good.
 * initPromise has already loaded composeFile with the right precedence
 * (sync, then local, then the default).
 */
function loadComposeFileAtStartup(savedPaths) {
  const parsed = parseComposeFile(composeFile);
  rootState = parsed.root;
  fileStatus = {warnings: parsed.warnings, errors: parsed.errors};

  // Resume a composition that survived the restart, if its saved positions
  // still exist in the tree; otherwise start from the root.
  const resumed = (composing && Array.isArray(savedPaths)) ?
      savedPaths.map((p) => stateAtPath(rootState, p)) : [];
  if (resumed.length > 0 && resumed.every((s) => s !== null)) {
    states = resumed;
  } else {
    states = [rootState];
    composing = false;
  }
  console.log(
      'Loaded compose file (%d characters).', lengthInCodepoints(composeFile));
}

/**
 * Sets the current states. Only their tree paths are persisted.
 * @param {Array<EventState!>!} value
 */
function setStates(value) {
  chrome.storage.session.set({'statePaths': value.map((s) => s.path)});
  states = value;
}

