/** @param {...*} args */
function dbg(...args) {
  if (debugLog) console.log('[composekey]', ...args);
}

/**
 * chrome.input.ime.keyEventHandled, logged. Only the first answer to a key event
 * is sent: the event listener answers early where it has to (see
 * https://crbug.com/826884), and Chrome reports a second answer as an error.
 * @param {string} requestId
 * @param {boolean} handled true = suppressed, false = passed to the app
 */
function keyEventHandled(requestId, handled) {
  const entry = unansweredKeys.get(requestId);
  if (entry === undefined) return;
  unansweredKeys.delete(requestId);
  entry[5] = Date.now() - entry[0];
  entry[6] = handled;
  dbg('   ->', handled ? 'suppressed' : 'passed through');
  chrome.input.ime.keyEventHandled(requestId, handled);
}

chrome.input.ime.onKeyEvent.addListener((engineID, keyData, requestId) => {
  logKey(keyData, requestId);
  // WAIT! First, make sure we've got all the settings in place before we do any
  // processing.
  initPromise.then(() => {
    const suppress = true;
    const propagate = false;

    if (debugLog) {
      const h = heldResult();
      dbg(keyData.type, JSON.stringify(keyData.key), keyData.code,
          'alt=' + keyData.altKey, 'altgr=' + keyData.altgrKey,
          'ctrl=' + keyData.ctrlKey, 'shift=' + keyData.shiftKey,
          'repeat=' + keyData.repeat, '| composing=' + composing,
          'candidates=' + states.length,
          'held=' + (h ? JSON.stringify(h.result.string + '|' + h.tail) : 'none'),
          '| composeKey=' + composeKey, 'keepModifier=' + keepModifier,
          'composeOnKeyUp=' + composeOnKeyUp);
    }

    const key = keyData.key;

    // If the compose key is a non-locking modifier, fire the compose event on
    // keyup so that it still works as a modifier. (Pressing some other key
    // while holding the compose key cancels the compose-on-key-up action.)
    //
    // Otherwise, fire the compose event on keydown so that we correctly
    // suppress its regular action.
    //
    // On ChromeOS, the Meta key by itself is an accelerator, so don't treat it
    // as a transient modifier.
    let isModifier = modifierKeys.has(key);
    const isLock = isModifier && key.endsWith('Lock');

    // A held key auto-repeats on ChromeOS: keydown after keydown, with no
    // `repeat` flag on the event. Each repeat of the
    // Compose key used to count as a fresh press, toggling compose on and off,
    // so hold-to-compose only worked if the sequence was typed before
    // repeating began. Repeats now get the same answer as the first keydown
    // and are otherwise ignored.
    //
    // If the keyup is ever lost, composeKeyDown would stay set and every
    // later press would look like a repeat, leaving compose dead. So it is
    // also cleared on focus changes (resetState), and by any other key that
    // arrives without the Compose key's modifier flag.
    if (composeKeyDown && keyData.code != composeKey &&
        modifierFlagOf(composeKey, keyData) === false) {
      setComposeKeyDown(false);
    }

    let isComposeEvent = false;
    if (keyData.code == composeKey) {
      if (keyData.type == 'keyup') {
        setComposeKeyDown(false);
        isComposeEvent = composeOnKeyUp;
      } else if (composeKeyDown) {
        keyEventHandled(
            requestId, keyDownSuppressed.has(key) ? suppress : propagate);
        return;
      } else {
        setComposeKeyDown(true);
        if (isModifier && keepModifier) {
          composeOnKeyUp = true;
          // Propagate the modifier event so that the key will correctly modify
          // other keystrokes.
          keyEventHandled(requestId, propagate);
          return;
        }
        isComposeEvent = true;
        isModifier = false;
      }
    } else if (keyData.type == 'keydown') {
      composeOnKeyUp = false;
    }

    if (keyData.type == 'keyup' && !isComposeEvent) {
      // Hold-to-compose: releasing the Compose key settles a pending
      // ambiguous sequence. (In tap mode the release comes before any
      // sequence key, when nothing can be pending yet.)
      if (keyData.code == composeKey && composing) {
        const h = heldResult();
        if (h !== null) {
          commitHeld(h, '', keyData);
          setStates([rootState]);
          setComposing(false);
          setHeld(null);
        }
      }
      // Never suppress a release, not even that of a key whose press was
      // suppressed. For the windows of Linux and Android apps, ChromeOS
      // (exo::Keyboard) keeps its own list of pressed keys, and ignores a press
      // of a key that is on it. It adds a key even if the input method consumed
      // the press, but never sees a release that the input method consumes. So
      // the key stayed on the list, and the next press of every key used in a
      // composition was lost. A release of a consumed press that is passed
      // through only updates the list; the app does not see it.
      keyDownSuppressed.delete(key);
      keyEventHandled(requestId, propagate);
      return;
    }

    const syms = isComposeEvent ? ['Multi_key'] : eventToSyms(keyData);

    for (const sym of syms) {
      let nextStates = [];
      let finalResult = null;

      for (let state of states) {
        for (let candidate of (state.nextKeys[sym] || [])) {
          if (!candidate.mods.match(keyData)) continue;

          nextStates.push(candidate);
          finalResult = candidate.result;
        }
      }

      if (nextStates.length == 0) {
        // The key does not extend any candidate sequence. If we haven't
        // consumed any keystrokes yet, or the key is a modifier for the next
        // keystroke, propagate it; otherwise, suppress it as normal.
        if (!composing || isModifier) {
          keyEventHandled(requestId, propagate);
          return;
        }

        // The key ends the composition. If a complete-but-ambiguous sequence
        // was waiting, this key decides that it is wanted after all.
        const h = heldResult();
        setStates([rootState]);
        setComposing(false);
        setHeld(null);
        if (h !== null && key != 'Escape') {
          if (isComposeEvent) {
            // Compose pressed again: commit, and consume the Compose key.
            commitHeld(h, '', keyData);
          } else if (isPrintable(keyData)) {
            // Commit everything in one call. Committing the held text and
            // letting the key through separately could reach the app in the
            // wrong order (cf. https://crbug.com/826884).
            keyEventHandled(requestId, suppress);
            commitHeld(h, key, keyData);
          } else {
            // Enter, Tab, arrows...: commit, then let the key act normally.
            // (The order has been checked on ChromeOS for Enter.)
            commitHeld(h, '', keyData);
            keyEventHandled(requestId, propagate);
            return;
          }
        }
        break;
      }

      if (finalResult !== null && canContinue(nextStates)) {
        // Complete, but a longer sequence is still possible: hold this result
        // and wait.
        const holder = nextStates.filter((c) => c.result).pop();
        setHeld({path: holder.path, tail: ''});
        setStates(nextStates);
        setComposing(true);
        continue;
      }

      if (finalResult !== null) {
        // Work around https://crbug.com/826884: suppress the keystroke
        // before calling commitText instead of waiting until we return.
        if (!isModifier || isLock) {
          keyEventHandled(requestId, true);
        }

        finalResult.send(keyData);
        setStates([rootState]);
        setComposing(false);
        setHeld(null);
        continue;
      }

      // Moving further past a held result: remember what was typed since, so
      // that if the longer sequence then fails, the held result and these
      // keys are committed rather than lost.
      if (held !== null && !isComposeEvent) {
        setHeld({path: held.path, tail: held.tail + (isPrintable(keyData) ? key : '')});
      }
      setStates(nextStates);
      setComposing(true);
    }

    if (isModifier && !isLock) {
      keyEventHandled(requestId, propagate);
      return;
    }

    if (keyData.type == 'keydown') {
      keyDownSuppressed.add(key);
    }
    keyEventHandled(requestId, suppress);
    return;
  }).catch((error) => {
    logEvent('EXCEPTION', String(error));
    throw error;
  });

  return;
});
