/**
 * Key events that have not been answered yet: request ID to log entry.
 * @type {Map<string, Array!>!}
 */
const unansweredKeys = new Map();

/** Keys currently down, by code; in memory only. */
const keysDown = new Set();

/**
 * Logs a key event, not which key it was.
 * @param {Object!} keyData
 * @param {string} requestId
 */
function logKey(keyData, requestId) {
  const entry = logEvent('key', keyData.type, 'unknown', '', null, null);
  unansweredKeys.set(requestId, entry);

  let flags = '';
  if (keyData.type == 'keydown') {
    if (keysDown.has(keyData.code)) flags += 'repeat ';
    keysDown.add(keyData.code);
  } else if (!keysDown.delete(keyData.code)) {
    flags += 'no-keydown ';  // it went elsewhere, or was lost
  }
  if (keyData.altKey) flags += 'alt ';
  if (keyData.ctrlKey) flags += 'ctrl ';
  if (composing) flags += 'composing ';
  if (held !== null) flags += 'held ';
  entry[4] = flags.trim();

  // A worker that has only just started does not know its settings yet.
  if (composeKey !== undefined) {
    entry[3] = keyData.code == composeKey ? 'compose' :
        modifierKeys.has(keyData.key) ? 'modifier' :
        [...String(keyData.key)].length == 1 ? 'char' : 'other';
  }
}

/**
 * The input context (text field) that composed text is committed to, or 0 if
 * none is focused.
 *
 * This must be persisted, not just kept in a global: Chrome stops an idle
 * service worker and starts a fresh one for the next key event, but does not
 * repeat onFocus for a field that is still focused. A worker that only kept
 * contextID in memory would wake up with 0, swallow the compose sequence and
 * commit nothing: compose quietly stops working until something (such as
 * switching input methods) fires onFocus again.
 * @type {number}
 */
let contextID = 0;

/**
 * @param {number} value
 */
function setContextID(value) {
  chrome.storage.session.set({'contextID': value});
  contextID = value;
}

// Wait for initPromise so that (a) resetState() never runs against a
// not-yet-loaded rootState when an onFocus is what woke the worker, and (b) the
// contextID restored from storage cannot overwrite the one this event sets.
chrome.input.ime.onFocus.addListener((context) => {
  const entry = logEvent(
      'focus', context.contextID, unansweredKeys.size, false, context.type);
  initPromise.then(() => {
    entry[4] = composing;
    resetState();
    setContextID(context.contextID);
  });
});
chrome.input.ime.onBlur.addListener((blurredID) => {
  const entry = logEvent('blur', blurredID, unansweredKeys.size, false, null);
  keysDown.clear();
  initPromise.then(() => {
    entry[4] = composing;
    resetState();
    setContextID(0);
  });
});

class Result {
  /**
   * At least one of {string, keysym} must be non-null.
   * @param {?string} string
   * @param {?string} keysym
   */
  constructor(string, keysym) {
    if (string == null) {
      const key = parseUnicodeSym(keysym) || symToEvent(keysym).key;
      if (!(/^\w{2,}$/.test(key))) {
        // The key is not plausible as a named key attribute value.
        // Treat it as a Unicode string.
        string = key;
        console.log('Treating key %s as Unicode string:', keysym, key);
      }
    }

    this.string = string;
    this.keysym = keysym;
    Object.freeze(this);
  }

  /**
   * Sends keydata to the input IME.
   * @param {{extensionId: string, keyCode: number, type: string}} keyData
   */
  send(keyData) {
    dbg('   commit', JSON.stringify(this.string), 'keysym=' + this.keysym,
        'contextID=' + contextID);
    const asText = this.string !== null && contextID !== 0;
    const entry = logEvent(
        'commit', asText ? 'text' : this.keysym !== null ? 'keysym' : 'NOTHING',
        contextID, null, null);
    const done = () => {
      entry[4] = Date.now() - entry[0];
      if (chrome.runtime.lastError) {
        entry[5] = String(chrome.runtime.lastError.message);
      }
    };
    if (asText) {
      chrome.input.ime.commitText(
          {
            contextID: contextID,
            text: this.string,
          },
          () => {
            done();
            if (chrome.runtime.lastError) {
              console.error('Error committing text:', chrome.runtime.lastError);
            }
          });
      return;
    }

    if (this.keysym == null) return;

    // Work around https://crbug.com/829396: instead of constructing a real
    // KeyboardEvent, send an object that just vaguely resembles one.
    const eventPrototype = Object.assign({}, keyData);
    delete eventPrototype.extensionId;
    delete eventPrototype.keyCode;
    const symEvent = symToEvent(this.keysym);
    delete symEvent.location;
    Object.assign(eventPrototype, symEvent);

    const down = Object.assign({}, eventPrototype);
    down.type = 'keydown';
    const up = Object.assign({}, keyData);
    up.type = 'keyup';

    chrome.input.ime.sendKeyEvents(
        {
          contextID: contextID,
          keyData: [down, up],
        },
        () => {
          done();
          if (chrome.runtime.lastError) {
            console.error(
                'Error sending key events:', chrome.runtime.lastError);
          }
        });
  }
}

class EventState {
  /**
   * @param {Modifiers!} mods
   * @param {boolean} builtin
   */
  constructor(mods, builtin, path = []) {
    this.mods = Object.freeze(mods);

    /**
     * Where this state sits in the tree: [keysym, index into nextKeys[keysym]]
     * steps from the root. Only these paths are persisted across worker
     * restarts (see setStates); the tree itself is re-parsed on start-up.
     * Persisting the tree meant serialising the whole table on every
     * keystroke, at a cost proportional to its size.
     * @type {!Array<!Array<string|number>>}
     */
    this.path = path;

    /** True if all sequences that pass through this state are built-in. */
    this.builtin = builtin;

    /** @type {?Result} */
    this.result = null;

    /**
     * Maps X11 keysyms to an array of events matching that keysym.
     * The events must be filtered by mods to obtain the final list of matches.
     *
     * @type {Object<string, Array<EventState!>!>!}
     */
    this.nextKeys = {};
  }

  /**
   * @param {{mods: Modifiers!, sym: string}} event
   * @param {boolean} builtin
   * @return {EventState!}
   */
  addEvent(event, builtin) {
    if (!builtin) {
      this.builtin = false;
    }

    let states = this.nextKeys[event.sym];
    if (states) {
      let last = states[states.length - 1];
      if (last.mods.equals(event.mods)) {
        if (!builtin) {
          last.builtin = false;
        }
        return last;
      }
    } else {
      states = [];
      this.nextKeys[event.sym] = states;
    }

    let state = new EventState(
        event.mods, builtin, [...this.path, [event.sym, states.length]]);
    states.push(state);
    return state;
  }
}

/**
 * Finds the state at `path` (see EventState.path) below `root`.
 * @param {EventState!} root
 * @param {*} path as read back from storage
 * @return {?EventState} null if the path does not exist in this tree.
 */
function stateAtPath(root, path) {
  if (!Array.isArray(path)) return null;
  let state = root;
  for (const step of path) {
    const next = Array.isArray(step) ? state.nextKeys[step[0]] : undefined;
    state = next ? next[step[1]] : undefined;
    if (!(state instanceof EventState)) return null;
  }
  return state;
}

/**
 * Adds the given sequence to root, pruning out the results of any existing
 * sequences that are an exact prefix of the new sequence.
 * @param {EventState!} root
 * @param {{
 *   events: Array<{mods: Modifiers!, sym: string}>!,
 *   result: Result!,
 *   builtin: boolean,
 * }} sequence
 * @return {{warning: ?string}}
 */
function addSequence(root, sequence) {
  let warning = null;
  let finalState = root;
  let prefixStates = [root];
  for (let event of sequence.events) {
    let nextPrefixStates = [];
    for (let state of prefixStates) {
      for (let candidate of (state.nextKeys[event.sym] || [])) {
        if (!candidate.mods.equals(event.mods)) continue;

        nextPrefixStates.push(candidate);
        if (candidate.builtin || !candidate.result) continue;

        // A shorter sequence that is a prefix of this one is kept: the key
        // handler waits for the next key to decide between them (see
        // `held`). It used to be suppressed here.
        let str = candidate.result.keysym;
        if (candidate.result.string !== null) {
          str = '“' + candidate.result.string + '”';
        }
        warning = 'Sequence extends an existing one (' + str +
            '); that one now waits for the next key before committing.';
      }
    }
    prefixStates = nextPrefixStates;

    finalState = finalState.addEvent(event, sequence.builtin);
  }

  for (let suffixStates of Object.values(finalState.nextKeys)) {
    if (warning !== null) break;
    for (let state of suffixStates) {
      if (state !== finalState && !state.builtin) {
        console.warn(
            'New sequence is a prefix of existing sequence(s):', state);
        warning = 'New sequence is a prefix of existing sequence(s); it ' +
            'waits for the next key before committing.';
        break;
      }
    }
  }
  finalState.result = sequence.result;

  return {warning: warning};
}

/**
 * Adds the built-in sequence definitions to root.
 * @param {EventState!} root
 */
function addBuiltinSequences(root) {
  let added = 0;
  for (const [keys, string] of builtinSequences) {
    let events = [{mods: modifiersAny, sym: 'Multi_key'}];

    for (const key of keys) {
      // Keys are typed characters, mapped with the same eventToSyms() that
      // maps real key events, so the two cannot disagree; "Multi_key" is a
      // further press of Compose.
      let syms = key == 'Multi_key' ? ['Multi_key'] : eventToSyms({
        key: key,
        location: KBE_DOM_KEY_LOCATION_STANDARD,
      });
      for (const sym of syms) {
        events.push({mods: modifiersAny, sym: sym});
      }
    }

    addSequence(root, {
      events: events,
      result: new Result(string, null),
      builtin: true,
    });
    added += 1;
  }

  console.log('Added %d built-in sequences.', added);
}

/**
 * Parses a leading event from an XCompose sequence definition line.
 *
 * @param {string} line
 * @return {{mods: Modifiers!, sym: string, rest: string}}
 * @throws {Error} if the line does not start with a syntactically-valid event.
 */
function parseEvent(line) {
  let rest = line;
  let match;
  let mods;
  if ((match = /^\s*None\s*/.exec(rest))) {
    rest = rest.substring(match[0].length);
    mods = modifiersNone;
  } else {
    mods = new Modifiers();
    if ((match = /^\s*[!]/.exec(rest))) {
      rest = rest.substring(match[0].length);
      Object.assign(mods, modifiersNone);
    }
    while (
        (match = /^\s*([~]\s*)?(Ctrl|Lock|Caps|Shift|Alt|Meta)\b/.exec(rest))) {
      rest = rest.substring(match[0].length);
      let val = match[1] ? false : true;
      switch (match[2]) {
        case 'Ctrl':
          mods.control = val;
          break;
        case 'Lock':
          // Fall through: Lock is a synonym for Caps.
        case 'Caps':
          mods.capsLock = val;
          break;
        case 'Shift':
          mods.shift = val;
          break;
        case 'Alt':
          mods.alt = val;
          break;
        case 'Meta':
          mods.meta = val;
          break;
        default:
          throw new Error('unreachable default case');
      }
    }
    mods = mods.equals(modifiersAny) ? modifiersAny : Object.freeze(mods);
  }

  if (!(match = /\s*<(\w+)>/.exec(rest))) {
    throw new Error('missing or invalid keysym in event');
  }
  rest = rest.substring(match[0].length);
  const sym = match[1];

  return {
    mods: mods,
    sym: sym,
    rest: rest,
  };
}

/**
 * Parses an XCompose sequence definition line.
 *
 * @param {string} line
 * @return {{events: Array<{mods: Modifiers!, sym: string}>!, result: Result!}}
 * @throws {Error} if the line is not a syntatically valid sequence.
 */
function parseSequence(line) {
  let event = parseEvent(line);
  let rest = event.rest;
  let events = [{mods: event.mods, sym: event.sym}];

  let match;
  // The result string may contain \" and \\ (X11's own Compose file uses
  // both, e.g. for the backslash and quotation-mark results); [^"]* used to
  // stop at the first \" and keep \\ as two characters.
  while (!(match = /^\s*:\s*(?:"((?:[^"\\]|\\.)*)"\s*)?(\w+)?\s*(?:#\s*.*)?$/
               .exec(rest))) {
    event = parseEvent(rest);
    rest = event.rest;
    events.push({mods: event.mods, sym: event.sym});
  }

  let string = match[1];
  const sym = match[2];
  if (string == null && sym == null) {
    throw new Error('missing or invalid result in sequence definition');
  }

  if (string) {
    // Convert octal and hex escapes to the corresponding Unicode strings.
    string = string.replace(
        /\\(?:(?:0?x([0-9a-fA-F]+))|([0-7]{1,3})|(.))/g,
        (match, hex, octal, other) => {
          if (other !== undefined) return other;  // \\ -> \, \" -> "
          return String.fromCodePoint(
              octal ? parseInt(octal, 8) : parseInt(hex, 16));
        });
  }

  return {events: events, result: new Result(string, sym)};
}

/**
 * @type {{
 *   warnings: Array<{line: string, message: string}>!,
 *   errors: Array<{line: string, message: string}>!,
 * }}
 */
let fileStatus = {
  warnings: [],
  errors: [],
};

/**
 * Parses a file in XCompose format to an EventState tree.
 *
 * @param {string} composeFile
 * @return {{
 *   root: EventState!,
 *   warnings: Array<{line: string, message: string}>!,
 *   errors: Array<{line: string, message: string}>!,
 * }}
 */
function parseComposeFile(composeFile) {
  let root = new EventState(modifiersAny);
  let warnings = [];
  let errors = [];

  let lines = composeFile.split('\n');
  let lineNumber = 0;
  let numCustom = 0;
  for (let line of lines) {
    lineNumber += 1;
    line = line.trim();
    if (line.length == 0 || /^(#.*)?$/.test(line)) {
      // Empty or comment-only line.
      continue;
    }

    if (/^include\s+"%L"\s*$/.test(line)) {
      addBuiltinSequences(root);
      continue;
    }

    let sequence;
    try {
      sequence = parseSequence(line);
    } catch (error) {
      errors.push({line: line, message: error.message});
      continue;
    }
    sequence.builtin = false;
    let result = addSequence(root, sequence);
    if (result.warning) {
      warnings.push({line: line, message: result.warning});
    }
    numCustom += 1;
  }

  if (numCustom > 0) {
    console.log('Added %d custom sequences.', numCustom);
  }
  return {
    root: root,
    warnings: warnings,
    errors: errors,
  };
}

