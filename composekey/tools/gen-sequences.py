#!/usr/bin/env python3
"""Build the extension's built-in Compose table from sequences/*.compose.

    tools/gen-sequences.py build
        Merge sequences/*.compose in file-name order and rewrite the generated
        blocks in service_worker.js and README.md.
    tools/gen-sequences.py import SOURCE FILE [--picks PICKS]
        (Re)create sequences/NN-SOURCE.compose from an upstream file. SOURCE is
        one of: x11, pointless, kragen, wincompose. Provenance (revision,
        licence) goes in the file header; supply it with --header.

Priority is the file-name order: the first file to define a sequence wins,
so an import can never change what a sequence the extension already shipped
produces. The order is: the original table, then X11, then everything else.

The generated table lists key characters rather than keysyms because the
extension maps each typed key to keysyms with eventToSyms(); converting with
that same function at load time means there is no second copy of the mapping
here that could drift. test/table.test.js checks the round trip for every
entry. Sequences that need a key a US keyboard cannot type are dropped at
import, and counted.
"""
import argparse
import json
import pathlib
import re
import sys

HERE = pathlib.Path(__file__).resolve().parent.parent        # .../composekey
SEQ_DIR = HERE / 'sequences'
WORKER = HERE / 'service_worker.js'
README = HERE / 'README.md'

BEGIN_JS = '// BEGIN GENERATED by tools/gen-sequences.py from sequences/*.compose'
END_JS = '// END GENERATED'
BEGIN_MD = '<!-- BEGIN GENERATED by tools/gen-sequences.py -->'
END_MD = '<!-- END GENERATED -->'

# X11 keysym names for printable ASCII (US keyboard, with or without Shift).
KEYSYM_CHAR = {
    'space': ' ', 'exclam': '!', 'quotedbl': '"', 'numbersign': '#',
    'dollar': '$', 'percent': '%', 'ampersand': '&', 'apostrophe': "'",
    'parenleft': '(', 'parenright': ')', 'asterisk': '*', 'plus': '+',
    'comma': ',', 'minus': '-', 'period': '.', 'slash': '/', 'colon': ':',
    'semicolon': ';', 'less': '<', 'equal': '=', 'greater': '>',
    'question': '?', 'at': '@', 'bracketleft': '[', 'backslash': '\\',
    'bracketright': ']', 'asciicircum': '^', 'underscore': '_', 'grave': '`',
    'braceleft': '{', 'bar': '|', 'braceright': '}', 'asciitilde': '~',
}
for _c in '0123456789abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ':
    KEYSYM_CHAR[_c] = _c
CHAR_KEYSYM = {v: k for k, v in KEYSYM_CHAR.items()}
COMPOSE = 'Multi_key'

LINE_RE = re.compile(r'^\s*((?:<[^>]*>\s*)+):\s*"((?:[^"\\]|\\.)*)"\s*(\w+)?\s*(?:#\s*(.*))?$')


def unescape(s):
    """XCompose string escapes: \\\\, \\", octal \\NNN, hex \\xNN / \\0xNN."""
    def rep(m):
        if m.group(1) is not None:
            return chr(int(m.group(1), 16))
        if m.group(2) is not None:
            return chr(int(m.group(2), 8))
        return m.group(3)
    return re.sub(r'\\(?:0?x([0-9a-fA-F]+)|([0-7]{1,3})|(.))', rep, s)


def key_of(sym):
    """A keysym as a key: an ASCII char, COMPOSE, or None if untypeable."""
    if sym == COMPOSE:
        return COMPOSE
    if sym in KEYSYM_CHAR:
        return KEYSYM_CHAR[sym]
    if len(sym) == 1 and ' ' <= sym <= '~':      # WinCompose/kragen: <.>, < >
        return sym
    m = re.fullmatch(r'U([0-9A-Fa-f]{4,6})', sym)
    if m and 0x20 <= int(m.group(1), 16) <= 0x7e:
        return chr(int(m.group(1), 16))
    return None


def parse(path):
    """Yield (keys, output, comment) for Compose-prefixed lines of an XCompose
    file; counts skipped lines in parse.skipped."""
    parse.skipped = {'untypeable': 0, 'not Compose-prefixed': 0, 'modifiers': 0,
                     'unparsed': 0}
    for raw in pathlib.Path(path).read_text(encoding='utf-8').splitlines():
        line = raw.strip()
        if not line or line.startswith('#') or line.startswith('include'):
            continue
        m = LINE_RE.match(line)
        if not m:
            parse.skipped['unparsed'] += 1
            continue
        syms = re.findall(r'<([^>]*)>', m.group(1))
        if re.search(r'[!~]|\b(Ctrl|Shift|Alt|Meta|Lock|Caps|None)\b',
                     re.sub(r'<[^>]*>', '', m.group(1))):
            parse.skipped['modifiers'] += 1
            continue
        if syms[0] != COMPOSE:
            parse.skipped['not Compose-prefixed'] += 1
            continue
        keys = [key_of(s) for s in syms[1:]]
        if not keys or None in keys:
            parse.skipped['untypeable'] += 1
            continue
        out = unescape(m.group(2))
        if not out:
            continue
        yield keys, out, (m.group(4) or '').strip()


def compose_line(keys, out, comment):
    syms = ' '.join('<%s>' % (k if k == COMPOSE else CHAR_KEYSYM[k]) for k in keys)
    esc = out.replace('\\', '\\\\').replace('"', '\\"')
    return '<Multi_key> %s : "%s"%s' % (syms, esc, ('  # ' + comment) if comment else '')


def seq_files():
    return sorted(p for p in SEQ_DIR.glob('*.compose'))


def merged():
    """[(keys, out, comment, source)] in priority order, first definition wins;
    plus a report of what each file contributed / lost."""
    seen = {}
    entries = []
    report = []
    merged.lost = []     # (file, sequence, its output, winning output, winner)
    for f in seq_files():
        added = dup_same = overridden = 0
        for keys, out, comment in parse(f):
            k = tuple(keys)
            if k in seen:
                if seen[k][0] == out:
                    dup_same += 1
                else:
                    overridden += 1
                    merged.lost.append((f.name, ''.join(keys), out) + seen[k])
                continue
            seen[k] = (out, f.stem)
            entries.append((keys, out, comment, f.stem))
            added += 1
        report.append((f.name, added, dup_same, overridden, dict(parse.skipped)))
    return entries, report


def replace_block(text, begin, end, body, path):
    i, j = text.find(begin), text.find(end)
    if i < 0 or j < i:
        sys.exit(f'{path}: generated-block markers not found ({begin!r})')
    j = text.index('\n', j)
    return text[:i] + begin + '\n' + body + end + text[j:]


def js_block(entries):
    rows = []
    for keys, out, comment, src in entries:
        tag = ' // ' + ((comment + '  ') if comment else '') + '[%s]' % src
        rows.append('  [%s, %s],%s' % (json.dumps(keys, ensure_ascii=False),
                                      json.dumps(out, ensure_ascii=False),
                                      tag.replace('\n', ' ')))
    return ('/**\n'
            ' * Built-in sequences: [keys, output]. Each key is a single typed\n'
            ' * character, or "Multi_key" for a further press of Compose.\n'
            ' * Generated: edit sequences/*.compose and run\n'
            ' * tools/gen-sequences.py build.\n'
            ' * @type {!Array<!Array>}\n'
            ' */\n'
            'const builtinSequences = Object.freeze([\n' + '\n'.join(rows) + '\n]);\n')


def md_seq(keys):
    # Not stripped: a sequence may end in a space (", " is cedilla).
    s = ''.join('Compose ' if k == COMPOSE else k for k in keys)
    if ' ' in s.replace('Compose ', ''):
        s = '"%s"' % s
    s = s.replace('|', '&#124;').replace('`', '&#96;')
    return s.replace('*', '\\*').replace('_', '\\_')


SECTION_TITLES = {}


def md_block(entries):
    out = []
    last = None
    for keys, o, comment, src in entries:
        if src != last:
            title = SECTION_TITLES.get(src) or header_title(src)
            out.append('\n### %s\n\nOutput | Sequence | Comment\n------ | -------- | -------' % title)
            last = src
        shown = '&nbsp;' if o.isspace() else o.replace('|', '&#124;')
        out.append('%s | %s | %s' % (shown, md_seq(keys), comment.replace('|', '&#124;')))
    return '\n'.join(out).lstrip('\n') + '\n'


def header_title(stem):
    f = SEQ_DIR / (stem + '.compose')
    for line in f.read_text(encoding='utf-8').splitlines():
        m = re.match(r'#\s*Title:\s*(.*)', line)
        if m:
            return m.group(1).strip()
    return stem


def generated():
    entries, report = merged()
    return entries, report, {
        WORKER: replace_block(WORKER.read_text(encoding='utf-8'),
                              BEGIN_JS, END_JS, js_block(entries), WORKER),
        README: replace_block(README.read_text(encoding='utf-8'),
                              BEGIN_MD, END_MD, md_block(entries), README),
    }


def cmd_build(args):
    entries, report, files = generated()
    for name, added, same, over, skipped in report:
        print(f'{name}: {added} added, {same} duplicates of earlier entries, '
              f'{over} overridden by earlier files')
    if args.verbose:
        for name, seq, out, win, winner in merged.lost:
            print(f'  {name}: {seq!r} -> {out} lost to {win} from {winner}')
    for path, text in files.items():
        path.write_text(text, encoding='utf-8')
    print(f'total: {len(entries)} built-in sequences')


def cmd_check(_args):
    """Exit 1 if a generated block is out of date; changes nothing."""
    _, _, files = generated()
    stale = [p.name for p, text in files.items()
             if p.read_text(encoding='utf-8') != text]
    if stale:
        sys.exit('stale generated blocks in %s: run tools/gen-sequences.py build'
                 % ', '.join(stale))
    print('generated blocks are up to date')


def cmd_import(args):
    picks = None
    if args.picks:
        picks = set()
        for line in pathlib.Path(args.picks).read_text(encoding='utf-8').splitlines():
            line = line.split('#', 1)[0].rstrip('\n')
            if line.strip():
                picks.add(line.strip())
    rows = []
    for keys, out, comment in parse(args.file):
        shown = ''.join('Compose ' if k == COMPOSE else k for k in keys)
        if picks is not None and shown not in picks:
            continue
        rows.append(compose_line(keys, out, comment))
    skipped = dict(parse.skipped)
    if picks is not None:
        found = {''.join('Compose ' if k == COMPOSE else k for k in keys)
                 for keys, _, _ in parse(args.file)}
        missing = sorted(picks - found)
        if missing:
            sys.exit(f'picks not found in {args.file}: {missing}')
    dest = SEQ_DIR / args.dest
    header = pathlib.Path(args.header).read_text(encoding='utf-8')
    dest.write_text(header.rstrip('\n') + '\n' +
                    f'# Imported by tools/gen-sequences.py: {len(rows)} sequences; '
                    f'skipped {skipped}\n\n' + '\n'.join(rows) + '\n',
                    encoding='utf-8')
    print(f'{dest.name}: {len(rows)} sequences; skipped {skipped}')


def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest='cmd', required=True)
    b = sub.add_parser('build')
    b.add_argument('--verbose', action='store_true',
                   help='list every entry that lost to a higher-priority file')
    sub.add_parser('check')
    imp = sub.add_parser('import')
    imp.add_argument('file', help='upstream XCompose-format file')
    imp.add_argument('dest', help='name of the sequences/*.compose file to write')
    imp.add_argument('--header', required=True,
                     help='file with the "# ..." provenance header to prepend')
    imp.add_argument('--picks', help='only these sequences (one per line, as typed)')
    args = ap.parse_args()
    {'build': cmd_build, 'check': cmd_check, 'import': cmd_import}[args.cmd](args)


if __name__ == '__main__':
    main()
