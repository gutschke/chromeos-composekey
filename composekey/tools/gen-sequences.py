#!/usr/bin/env python3
"""Build the extension's built-in Compose table from sequences/*.compose.

    tools/gen-sequences.py build
        Merge sequences/*.compose in file-name order and rewrite the generated
        blocks in service_worker.js and README.md.
    tools/gen-sequences.py import SOURCE FILE [--picks PICKS]
        (Re)create sequences/NN-SOURCE.compose from an upstream file. SOURCE is
        one of: x11, pointless, kragen, wincompose. Provenance (revision,
        licence) goes in the file header; supply it with --header.

Priority is the file-name order: the first file to define a sequence wins,
so an import can never change what a sequence the extension already shipped
produces. The order is: the original table, then X11, then everything else.

The generated table lists key characters rather than keysyms because the
extension maps each typed key to keysyms with eventToSyms(); converting with
that same function at load time means there is no second copy of the mapping
here that could drift. test/table.test.js checks the round trip for every
entry. Sequences that need a key a US keyboard cannot type are dropped at
import, and counted.
"""
